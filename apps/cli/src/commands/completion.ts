// commands/completion.ts — generate shell tab completion script

import { HOSTED_CONNECTION_PROVIDERS } from "draft-core/integrations/hosted-connections";
import { DISCONNECT_PROVIDERS, PROVIDER_LABELS } from "../integrations/types.ts";

export async function runCompletion(args: string[]): Promise<void> {
  const shell = args.includes("--zsh") ? "zsh" : "bash";

  if (args.includes("--help")) {
    console.log("Usage: draft completion [--bash | --zsh]");
    console.log("");
    console.log("Generate a shell completion script and add it to your shell config:");
    console.log("  bash:  draft completion >> ~/.bashrc && source ~/.bashrc");
    console.log("  zsh:   draft completion --zsh >> ~/.zshrc && source ~/.zshrc");
    process.exit(0);
  }

  if (shell === "zsh") {
    process.stdout.write(zshCompletion());
  } else {
    process.stdout.write(bashCompletion());
  }
}

// ── Bash completion ────────────────────────────────────────────────────────────

function bashCompletion(): string {
  const providers = HOSTED_CONNECTION_PROVIDERS.join(" ");
  const disconnectProviders = DISCONNECT_PROVIDERS.filter((provider) => provider !== "claude-code").join(" ");
  return `# Draft CLI bash completion
# Generated by: draft completion
# Add to ~/.bashrc:  draft completion >> ~/.bashrc && source ~/.bashrc

_draft_completion() {
  local cur prev commands flags
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"
  commands="add auth context people routines activity sources sessions skills connections update uninstall completion"

  if [[ "\$cur" == -* ]]; then
    case "\${COMP_WORDS[1]}:\${COMP_WORDS[2]}" in
      auth:login) flags="--force --json" ;;
      connections:connect) flags="--json --wait --no-open --workspace-key --credential-stdin --credential-fd" ;;
      connections:list) flags="--json" ;;
      connections:disconnect) flags="--json --workspace-key" ;;
      activity:list) flags="--cursor --json" ;;
      sessions:list) flags="--provider --since --until --limit --cursor --json" ;;
      sessions:read) flags="--after-seq --limit --json" ;;
      sources:list) flags="--provider --type --since --until --limit --cursor --json" ;;
      routines:*) flags="--on --github --github-access --no-github --schedule --no-schedule --no-triggers --enable --disable --disabled --wait --session-id --transcript --cursor --in --at --once --upcoming --fired --mine --json" ;;
      *) flags="" ;;
    esac
    COMPREPLY=( $(compgen -W "\$flags" -- "\$cur") )
    return 0
  fi

  case "\$prev" in
    draft)
      COMPREPLY=( $(compgen -W "\$commands" -- "\$cur") )
      return 0
      ;;
    add)
      COMPREPLY=( $(compgen -W "claude-code codex cursor openclaw hermes" -- "\$cur") )
      return 0
      ;;
    auth)
      COMPREPLY=( $(compgen -W "login logout whoami" -- "\$cur") )
      return 0
      ;;
    context)
      COMPREPLY=( $(compgen -W "list read export" -- "\$cur") )
      return 0
      ;;
    people)
      COMPREPLY=( $(compgen -W "find create pending approve reject notify" -- "\$cur") )
      return 0
      ;;
    routines)
      COMPREPLY=( $(compgen -W "list options create update delete run runs" -- "\$cur") )
      return 0
      ;;
    activity)
      COMPREPLY=( $(compgen -W "list" -- "\$cur") )
      return 0
      ;;
    sources)
      COMPREPLY=( $(compgen -W "search read" -- "$cur") )
      return 0
      ;;
    sessions)
      COMPREPLY=( $(compgen -W "enable disable status list read search" -- "\$cur") )
      return 0
      ;;
    skills)
      COMPREPLY=( $(compgen -W "list read add update remove" -- "\$cur") )
      return 0
      ;;
    connections)
      COMPREPLY=( $(compgen -W "list connect disconnect slack" -- "\$cur") )
      return 0
      ;;
    connect)
      if [[ "\${COMP_WORDS[1]}" == "connections" ]]; then
        COMPREPLY=( $(compgen -W "${providers}" -- "\$cur") )
        return 0
      fi
      ;;
    disconnect)
      if [[ "\${COMP_WORDS[1]}" == "connections" ]]; then
        COMPREPLY=( $(compgen -W "${disconnectProviders}" -- "\$cur") )
        return 0
      fi
      ;;
    completion)
      COMPREPLY=( $(compgen -W "--bash --zsh" -- "\$cur") )
      return 0
      ;;
  esac

  COMPREPLY=( $(compgen -W "\$commands" -- "\$cur") )
}

complete -F _draft_completion draft
`;
}

// ── Zsh completion ─────────────────────────────────────────────────────────────

function zshCompletion(): string {
  const providers = Object.entries(PROVIDER_LABELS).map(([provider, label]) => `'${provider}:${label}'`).join(" ");
  const disconnectProviders = DISCONNECT_PROVIDERS
    .filter((provider) => provider !== "claude-code")
    .map((provider) => `'${provider}:${PROVIDER_LABELS[provider]}'`)
    .join(" ");
  return `# Draft CLI zsh completion
# Generated by: draft completion --zsh
# Add to ~/.zshrc:  draft completion --zsh >> ~/.zshrc && source ~/.zshrc

_draft() {
  local state

  _arguments \\
    '1: :->command' \\
    '*: :->args'

  case \$state in
    command)
      local commands=(
        'add:Add Draft to a CLI tool'
        'auth:Authenticate with the Draft control plane'
        'context:Read workspace context'
        'people:Find, add and message the people in the workspace'
        'routines:Manage routines'
        'activity:What the workspace agents have run'
        'sources:Search and read cross-provider source evidence'
        'sessions:Manage coding session capture'
        'skills:Discover and manage the company skill marketplace'
        'connections:Manage hosted connections'
        'update:Update the Draft CLI'
        'uninstall:Remove the Draft CLI'
        'completion:Generate shell completion script'
      )
      _describe 'command' commands
      ;;
    args)
      case \$words[2] in
        add)
          local tools=('claude-code:Add Draft to Claude Code' 'codex:Add Draft to Codex' 'cursor:Add Draft to Cursor' 'openclaw:Add Draft to OpenClaw' 'hermes:Add Draft to Hermes')
          _describe 'tool' tools
          ;;
        auth)
          if (( CURRENT == 3 )); then
            local subcmds=('login:Sign in' 'logout:Sign out' 'whoami:Show the current identity')
            _describe 'subcommand' subcmds
          else
            _arguments '--json[Print machine-readable output]' '--force[Start a new sign-in even when a session exists]'
          fi
          ;;
        context)
          local subcmds=('list:List available context dimensions' 'read:Print one or more context dimensions' 'export:Export the full context as markdown files')
          _describe 'subcommand' subcmds
          ;;
        people)
          local subcmds=('find:Find people' 'create:Add a teammate' 'pending:List people waiting for approval' 'approve:Approve a pending person' 'reject:Reject a pending person' 'notify:Send a message to a person')
          _describe 'subcommand' subcmds
          ;;
        activity)
          local subcmds=('list:What the workspace agents have run')
          _describe 'subcommand' subcmds
          ;;
        routines)
          if (( CURRENT == 3 )); then
            local subcmds=('list:List routines, including one-shots with --once' 'options:Show the options for routines' 'create:Create a routine: once, on a schedule, or on an event' 'update:Update a routine' 'delete:Delete a routine' 'run:Run a routine now' 'runs:List the runs of a routine')
            _describe 'subcommand' subcmds
          else
            _arguments \\
              '--in=[Run once after a duration, such as 2h]:duration:' \\
              '--at=[Run once at an ISO time with an offset]:time:' \\
              '--once[Show one-shot routines]' \\
              '--upcoming[Show one-shots that have not run yet]' \\
              '--fired[Show one-shots that have run]' \\
              '--mine[Show only the routines you made]' \\
              '--on=[Trigger event]:event:' \\
              '--github=[GitHub repository]:repository:' \\
              '--github-access=[GitHub access level]:access:' \\
              '--no-github[Give the routine no GitHub access]' \\
              '--schedule[Turn the schedule on]' \\
              '--no-schedule[Run only on triggers and Run now]' \\
              '--no-triggers[Remove the triggers]' \\
              '--enable[Enable the routine]' \\
              '--disable[Disable the routine]' \\
              '--disabled[Save the routine turned off]' \\
              '--wait[Wait for the run to finish]' \\
              '--session-id=[Session id]:id:' \\
              '--transcript[Show the run transcript]' \\
              '--cursor=[Page cursor]:cursor:' \\
              '--json[Print machine-readable output]'
          fi
          ;;
        sources)
          local subcmds=('search:Search source evidence' 'read:Read one source representation')
          _describe 'subcommand' subcmds
          ;;
        sessions)
          local subcmds=('enable:Enable session capture' 'disable:Disable session capture' 'status:Show capture status' 'list:List sessions' 'read:Read a session' 'search:Search sessions')
          _describe 'subcommand' subcmds
          ;;
        skills)
          local subcmds=('list:List the skill marketplace' 'read:Read one skill' 'add:Add a skill' 'update:Update a skill' 'remove:Remove a skill')
          _describe 'subcommand' subcmds
          ;;
        connections)
          if (( CURRENT == 3 )); then
            local subcmds=('list:Show each connection and what it unlocks' 'connect:Connect a hosted connection' 'disconnect:Disconnect a hosted connection' 'slack:Manage Slack channels')
            _describe 'subcommand' subcmds
          elif [[ \$words[3] == 'connect' ]]; then
            if [[ \$PREFIX == -* ]]; then
              _arguments '--json[Print the link as one JSON line]' '--wait[Wait until connected]' '--no-open[Do not open a browser]'
            else
            local providers=(${providers})
              _describe 'provider' providers
            fi
          elif [[ \$words[3] == 'disconnect' ]]; then
            local providers=(${disconnectProviders})
            _describe 'provider' providers
          fi
          ;;
        update)
          _arguments '--check[Check without installing]'
          ;;
        uninstall)
          _arguments '--yes[Skip the confirmation prompt]'
          ;;
        completion)
          _arguments '--bash[Generate bash completion]' '--zsh[Generate zsh completion]'
          ;;
      esac
      ;;
  esac
}

compdef _draft draft
`;
}
