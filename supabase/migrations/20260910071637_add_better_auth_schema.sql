  check (command in (
    'sessions.list', 'sessions.read', 'sessions.search',
    'skills.list', 'skills.read',
    'context.read',
    'mcp.context.list', 'mcp.context.read',
    'mcp.sessions.list', 'mcp.sessions.read', 'mcp.sessions.search',
    'mcp.skills.list', 'mcp.skills.read'
  ));
