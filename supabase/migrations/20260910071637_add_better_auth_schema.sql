-- Better Auth's own tables (OAuth 2.1 AS for the remote MCP server — plan
-- 0053). Isolated in a dedicated schema, never exposed through PostgREST:
-- Draft's REST API (public.*, PostgREST/Supabase client) and Better Auth
-- (better_auth.*, a direct pg connection) are two separate identity systems
-- that only meet at the id-matched `better_auth.user.id = public.users.id`
-- convention, enforced by application code (the Supabase-session-bridge
-- endpoint), not a foreign key -- the two live in different schemas Postgres
-- cannot cross-reference, and not every Supabase user has a better_auth.user
-- row (see below).
--
-- No signup-time trigger populates better_auth.user. Provisioning is lazy:
-- backend/src/auth/better-auth-supabase-bridge-plugin.ts upserts the row on
-- a user's first MCP login. Most Supabase users never connect an MCP client
-- and never get a better_auth.user row at all -- don't assume one exists.
--
-- RLS is not the isolation mechanism here (these tables are never queried
-- through PostgREST, so `anon`/`authenticated` are never granted schema
-- `usage` in the first place -- that absence is the boundary). A dedicated
-- Postgres role is created for Better Auth's direct `pg` connection, scoped
-- to only this schema, least-privilege rather than reusing the `postgres`
-- superuser role the way Supabase's own internal tooling does.
--
-- Generated by calling better-auth's own `getMigrations().compileMigrations()`
-- against the real `betterAuth()` config (see backend/src/auth/better-auth.ts)
-- and verified end-to-end against a local Supabase Postgres: applied via
-- `runMigrations()`, confirmed all 12 tables land in `better_auth` (not
-- `public`) via `search_path=better_auth,public` on the connection, then
-- dropped again before this file was hand-placed here, per this repo's
-- generate-only convention for Better Auth's migrations.

create schema if not exists better_auth;

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'better_auth_service') then
    create role better_auth_service login password null;
  end if;
end
$$;

grant usage on schema better_auth to better_auth_service;
alter default privileges in schema better_auth grant all on tables to better_auth_service;
alter default privileges in schema better_auth grant all on sequences to better_auth_service;

set search_path to better_auth;

